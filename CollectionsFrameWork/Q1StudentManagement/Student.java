package CollectionsFrameWork.Q1StudentManagement;

public class Student {
    int id;
    String name;
    int age;
    double grade;
    String branch;

    Student(int id, String name, int age, double grade, String branch) {
        this.id = id;
        this.name = name;
        this.age = age;
        this.grade = grade;
        this.branch = branch;
    }
}
